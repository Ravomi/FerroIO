use crate::config::{EnvConfig, ProjectMeta, RavomConfig};
use crate::registry::registry;
use crate::zephyr::{
    is_zephyr_framework, known_zephyr_board, scaffold_zephyr_project, ZephyrConfig, ZephyrLang,
};
use crate::{CoreError, Result};
use std::collections::BTreeMap;
use std::fs;
use std::path::{Path, PathBuf};

/// Summary of an initialized RavomIO project.
#[derive(Debug, Clone)]
pub struct InitResult {
    pub root: PathBuf,
    pub board_id: String,
    pub framework: String,
    pub manifest_path: PathBuf,
}

/// Known `(flash_origin, ram_origin)` base addresses for ARM Cortex-M platforms
/// whose starter Rust project should include a flashable `memory.x` + `link.x`.
fn cortex_m_memory_origins(platform: &str) -> Option<(u32, u32)> {
    match platform {
        "ststm32" | "gd32" => Some((0x0800_0000, 0x2000_0000)),
        "nordicnrf52" | "nordicnrf51" => Some((0x0000_0000, 0x2000_0000)),
        _ => None,
    }
}

fn format_memory_size(bytes: u64) -> String {
    if bytes > 0 && bytes.is_multiple_of(1024) {
        format!("{}K", bytes / 1024)
    } else {
        bytes.to_string()
    }
}

fn scaffold_cortex_m_linker_scripts(
    dir: &Path,
    flash_origin: u32,
    flash_bytes: u64,
    ram_origin: u32,
    ram_bytes: u64,
) -> Result<()> {
    let memory_x = format!(
        "/* Auto-generated by RavomIO from board metadata. */\n\
         MEMORY\n\
         {{\n\
             FLASH : ORIGIN = 0x{flash_origin:08X}, LENGTH = {}\n\
             RAM   : ORIGIN = 0x{ram_origin:08X}, LENGTH = {}\n\
         }}\n",
        format_memory_size(flash_bytes),
        format_memory_size(ram_bytes),
    );
    fs::write(dir.join("memory.x"), memory_x)?;

    let link_x = "\
/* Minimal RavomIO Cortex-M starter linker script.
 * Replace or remove this file when switching to cortex-m-rt / embassy.
 */
INCLUDE memory.x

ENTRY(_start)

_stack_start = ORIGIN(RAM) + LENGTH(RAM);

SECTIONS
{
    .vector_table ORIGIN(FLASH) :
    {
        LONG(_stack_start);
        LONG(_start);
    } > FLASH

    .text :
    {
        *(.text .text.*)
    } > FLASH

    .rodata :
    {
        *(.rodata .rodata.*)
    } > FLASH

    .data : ALIGN(4)
    {
        *(.data .data.*)
    } > RAM AT > FLASH

    .bss (NOLOAD) : ALIGN(4)
    {
        *(.bss .bss.*)
        *(COMMON)
    } > RAM

    /DISCARD/ :
    {
        *(.ARM.exidx*)
        *(.ARM.extab*)
    }
}
";
    fs::write(dir.join("link.x"), link_x)?;
    Ok(())
}

/// Initialize a PlatformIO-style project layout (`ravom.toml`, `src/`, `include/`, `lib/`).
pub fn init_project(dir: &Path, board_id: &str, framework: Option<&str>) -> Result<InitResult> {
    let board = registry().resolve(board_id, None)?.clone();

    let fw = framework.unwrap_or(&board.default_framework).to_string();
    fs::create_dir_all(dir)?;

    let manifest_path = dir.join("ravom.toml");
    if manifest_path.exists() {
        return Err(CoreError::AlreadyInitialized(manifest_path));
    }

    for sub in ["src", "include", "lib"] {
        fs::create_dir_all(dir.join(sub))?;
    }

    let project_name = dir
        .file_name()
        .and_then(|n| n.to_str())
        .unwrap_or("ravomio-app")
        .to_string();

    let is_zephyr = is_zephyr_framework(&fw);
    let zephyr_lang = if matches!(
        fw.to_ascii_lowercase().as_str(),
        "zephyr-rust" | "zephyr_rust"
    ) {
        ZephyrLang::Rust
    } else {
        ZephyrLang::C
    };
    let manifest_framework = if is_zephyr {
        "zephyr".to_string()
    } else {
        fw.clone()
    };
    let zephyr_cfg = if is_zephyr {
        let zboard = board
            .zephyr_board
            .clone()
            .or_else(|| known_zephyr_board(&board.id).map(str::to_string));
        Some(ZephyrConfig {
            board: zboard,
            lang: zephyr_lang,
            ..ZephyrConfig::default()
        })
    } else {
        None
    };

    let mut env = BTreeMap::new();
    env.insert(
        board.id.to_string(),
        EnvConfig {
            platform: board.platform.to_string(),
            board: board.id.to_string(),
            framework: manifest_framework.clone(),
            upload_protocol: board
                .probe_rs_chip
                .as_ref()
                .map(|_| "probe-rs".to_string())
                .or_else(|| is_zephyr.then(|| "west".to_string())),
            monitor_speed: Some(115200),
            zephyr: zephyr_cfg,
            ..EnvConfig::default()
        },
    );

    let cfg = RavomConfig {
        project: ProjectMeta {
            name: Some(project_name.clone()),
            default_envs: Some(vec![board.id.to_string()]),
        },
        env,
    };

    fs::write(&manifest_path, cfg.to_toml_string()?)?;

    if is_zephyr {
        scaffold_zephyr_project(dir, &project_name, &board, zephyr_lang)?;
    } else if let Some(plugin) = ravom_plugin::find_framework_plugin(&fw) {
        for (rel_path, contents) in
            plugin.scaffold_files(&project_name, &board.id, board.rust_target.as_deref())
        {
            let full_path = dir.join(&rel_path);
            if let Some(parent) = full_path.parent() {
                fs::create_dir_all(parent)?;
            }
            fs::write(full_path, contents)?;
        }
        if plugin.kind() == ravom_plugin::FrameworkKind::RustCargo {
            if let (Some(target), Some((flash_origin, ram_origin)), Some(flash), Some(ram)) = (
                &board.rust_target,
                cortex_m_memory_origins(&board.platform),
                board.flash_bytes,
                board.ram_bytes,
            ) {
                scaffold_cortex_m_linker_scripts(dir, flash_origin, flash, ram_origin, ram)?;
                fs::create_dir_all(dir.join(".cargo"))?;
                fs::write(
                    dir.join(".cargo/config.toml"),
                    format!(
                        "[build]\ntarget = \"{target}\"\n\n[target.{target}]\nrustflags = [\"-C\", \"link-arg=-Tlink.x\"]\n"
                    ),
                )?;
            }
        }
    } else {
        fs::write(
            dir.join("Cargo.toml"),
            format!(
                "[package]\nname = \"{}\"\nversion = \"0.1.0\"\nedition = \"2021\"\n\n[dependencies]\n",
                project_name.replace(' ', "-")
            ),
        )?;
        let is_linux_userland = matches!(board.platform.as_str(), "linux_sbc" | "linux_arm")
            || fw.eq_ignore_ascii_case("linux");
        if let Some(target) = &board.rust_target {
            fs::create_dir_all(dir.join(".cargo"))?;
            let has_linker_script =
                if let (Some((flash_origin, ram_origin)), Some(flash), Some(ram)) = (
                    cortex_m_memory_origins(&board.platform),
                    board.flash_bytes,
                    board.ram_bytes,
                ) {
                    scaffold_cortex_m_linker_scripts(dir, flash_origin, flash, ram_origin, ram)?;
                    true
                } else {
                    false
                };
            let cargo_cfg = if has_linker_script {
                format!(
                    "[build]\ntarget = \"{target}\"\n\n[target.{target}]\nrustflags = [\"-C\", \"link-arg=-Tlink.x\"]\n"
                )
            } else if is_linux_userland {
                format!(
                    "[build]\ntarget = \"{target}\"\n\n[target.{target}]\nlinker = \"rust-lld\"\n"
                )
            } else {
                format!("[build]\ntarget = \"{target}\"\n")
            };
            fs::write(dir.join(".cargo/config.toml"), cargo_cfg)?;
        }
        let starter_src = if is_linux_userland {
            format!(
                "// RavomIO Linux userland starter for `{}` (framework: {fw})\n\
                 fn main() {{\n\
                     println!(\"RavomIO Linux app booted on {}\");\n\
                 }}\n",
                board.id, board.id
            )
        } else {
            ravom_plugin::find_framework_plugin(&fw)
                .map(|plugin| plugin.starter_main_rs(&board.id))
                .unwrap_or_else(|| {
                    format!(
                        "// RavomIO starter for `{}` (framework: {fw})\n#![no_std]\n#![no_main]\n\nuse core::panic::PanicInfo;\n\n#[panic_handler]\nfn panic(_info: &PanicInfo) -> ! {{\n    loop {{}}\n}}\n\n#[no_mangle]\npub extern \"C\" fn _start() -> ! {{\n    loop {{}}\n}}\n",
                        board.id
                    )
                })
        };
        fs::write(dir.join("src/main.rs"), starter_src)?;
        fs::write(dir.join(".gitignore"), "target/\n.ravom/\n")?;
    }

    Ok(InitResult {
        root: dir.to_path_buf(),
        board_id: board.id.to_string(),
        framework: manifest_framework,
        manifest_path,
    })
}

#[cfg(test)]
mod tests {
    use super::*;

    #[test]
    fn init_creates_platformio_like_layout() {
        let tmp = tempfile::tempdir().expect("tempdir");
        let res = init_project(tmp.path(), "stm32f401ccu6", None)
            .expect("init_project should succeed for stm32f401ccu6");

        assert!(res.manifest_path.exists());
        for file in [
            "Cargo.toml",
            ".cargo/config.toml",
            "memory.x",
            "link.x",
            "src/main.rs",
            ".gitignore",
        ] {
            assert!(tmp.path().join(file).exists(), "{file} missing");
        }
        let memory_x = fs::read_to_string(tmp.path().join("memory.x")).expect("memory.x");
        assert!(memory_x.contains("ORIGIN = 0x08000000"), "{memory_x}");
        assert!(memory_x.contains("ORIGIN = 0x20000000"), "{memory_x}");
        let cargo_cfg =
            fs::read_to_string(tmp.path().join(".cargo/config.toml")).expect("config.toml");
        assert!(cargo_cfg.contains("link-arg=-Tlink.x"), "{cargo_cfg}");
        assert!(tmp.path().join("include").is_dir());
        assert!(tmp.path().join("lib").is_dir());

        let cfg = RavomConfig::load_from_dir(tmp.path()).expect("manifest parses");
        let (_, env) = cfg.resolve_env(None).expect("default env");
        assert_eq!(env.upload_protocol.as_deref(), Some("probe-rs"));
    }

    #[test]
    fn init_refuses_to_overwrite_and_rejects_unknown_boards() {
        let tmp = tempfile::tempdir().expect("tempdir");
        init_project(tmp.path(), "bluepill_f103c8", None).expect("first init");
        assert!(matches!(
            init_project(tmp.path(), "bluepill_f103c8", None),
            Err(CoreError::AlreadyInitialized(_))
        ));
        assert!(matches!(
            init_project(tmp.path(), "no_such_board_xyz", None),
            Err(CoreError::UnknownBoard(_))
        ));
    }

    #[test]
    fn init_for_board_without_probe_rs_leaves_upload_protocol_unset() {
        let tmp = tempfile::tempdir().expect("tempdir");
        init_project(tmp.path(), "atmelavr/uno", Some("arduino")).expect("init uno");
        let cfg = RavomConfig::load_from_dir(tmp.path()).expect("manifest parses");
        let (_, env) = cfg.resolve_env(None).expect("default env");
        assert_eq!(env.upload_protocol, None);
        assert_eq!(env.platform, "atmelavr");
        assert!(tmp.path().join("src/main.cpp").exists());
        assert!(!tmp.path().join("Cargo.toml").exists());
    }

    #[test]
    fn init_for_linux_sbc_generates_std_main() {
        let tmp = tempfile::tempdir().expect("tempdir");
        init_project(tmp.path(), "raspberrypi_zero2w", None).expect("init linux sbc");
        let main_rs = fs::read_to_string(tmp.path().join("src/main.rs")).expect("main.rs");
        assert!(main_rs.contains("fn main()"), "{main_rs}");
        assert!(!main_rs.contains("#![no_std]"), "{main_rs}");
        assert!(!tmp.path().join("link.x").exists());
        let cargo_cfg =
            fs::read_to_string(tmp.path().join(".cargo/config.toml")).expect("config.toml");
        assert!(cargo_cfg.contains("linker = \"rust-lld\""), "{cargo_cfg}");
    }
}
