#!/usr/bin/env bash
# Regenerate the probe-rs target snapshot used to validate `probe_rs_chip`
# in board definitions, then re-resolve every board against it.
#
#   scripts/update-probe-rs-targets.sh            # uses `probe-rs` from PATH
#
# Only variant names (indented under "Variants:") are kept: family names such
# as `SAMD21` are ambiguous and rejected by `probe-rs download --chip`.
set -euo pipefail
cd "$(dirname "$0")/.."

out=crates/ravom-core/data/probe-rs-targets.txt
version=$(probe-rs --version | awk '{print $2}')
{
  echo "# probe-rs target variants snapshot (generated by scripts/update-probe-rs-targets.sh)"
  echo "# probe-rs ${version}"
  probe-rs chip list 2>/dev/null | awk '/^ {8}[^ ]/{gsub(/^ +| +$/,""); print}' | LC_ALL=C sort -u
} > "$out"
echo "wrote $(grep -vc '^#' "$out") targets to $out"

cargo run -q -p ravom-cli -- boards --normalize-chips boards
