#!/usr/bin/env bash
set -euo pipefail

log() {
  printf '[paseo-setup] %s\n' "$*"
}

if [ -d "$HOME/.cargo/bin" ]; then
  export PATH="$HOME/.cargo/bin:$PATH"
fi

if [ -f .env ]; then
  set -a
  # shellcheck disable=SC1091
  . ./.env
  set +a
fi

# 1. Initialize and sync git submodules (docs/guide & examples)
if [ -f .gitmodules ]; then
  log "Initializing git submodules (docs/guide, examples)..."
  git submodule update --init --recursive
fi

# 2. Ensure Rust components & cross-compile target used by CI tests
if command -v rustup >/dev/null 2>&1; then
  INSTALLED_COMPONENTS="$(rustup component list --installed 2>/dev/null || true)"
  for comp in rustfmt clippy; do
    if ! printf '%s\n' "$INSTALLED_COMPONENTS" | grep -q "^${comp}"; then
      log "Installing rustup component: ${comp}"
      rustup component add "$comp" || log "WARN: failed to install ${comp} (offline?)"
    fi
  done

  INSTALLED_TARGETS="$(rustup target list --installed 2>/dev/null || true)"
  if ! printf '%s\n' "$INSTALLED_TARGETS" | grep -qx "thumbv7m-none-eabi"; then
    log "Installing rustup target: thumbv7m-none-eabi (for cross-compile tests)"
    rustup target add thumbv7m-none-eabi || log "WARN: failed to install thumbv7m-none-eabi (offline?)"
  fi
fi

# 3. Optional shared Cargo target dir across worktrees when opted in
if [ "${RAVOM_SHARED_TARGET:-0}" = "1" ] && [ -n "${PASEO_SOURCE_CHECKOUT_PATH:-}" ]; then
  cat > .env.local <<EOF
# Auto-generated by scripts/paseo-setup.sh
CARGO_TARGET_DIR=${PASEO_SOURCE_CHECKOUT_PATH}/target
EOF
  log "Configured shared CARGO_TARGET_DIR in .env.local"
fi

# 4. Warm Cargo dependency cache (shares ~/.cargo registry across worktrees)
if command -v cargo >/dev/null 2>&1; then
  log "Fetching Cargo workspace dependencies..."
  cargo fetch --locked || cargo fetch
else
  log "WARN: cargo not found in PATH; skipping Rust dependency fetch."
fi

log "Worktree setup complete."
